export interface TemplateVariable {
  key: string;
  label: string;
}

/** Biến dùng được của mẫu; mẫu không có trong bảng (tự thêm vào DB) trả null, tức không kiểm được. */
export function variablesOf(code: string): TemplateVariable[] | null {
  const keys = TEMPLATE_VARIABLES[code];
  return keys ? keys.map((key) => ({ key, label: VARIABLE_LABELS[key] ?? key })) : null;
}

/**
 * Lỗi gõ biến trong nội dung mẫu, nói bằng chữ thường để chủ cửa hàng sửa được; chuỗi rỗng = hợp lệ.
 * Bắt ba lỗi: biến mã không điền cho mẫu này, tên biến gõ sai (có dấu cách, dấu tiếng Việt...) và ngoặc đơn `{ten}` thay vì ngoặc đôi.
 */
export function templateVariableProblem(code: string, body: string): string {
  const allowed = TEMPLATE_VARIABLES[code];
  const list = allowed?.length ? allowed.map((k) => `{{${k}}}`).join(', ') : 'không có biến nào';
  const hint = `Mẫu này dùng được: ${list}.`;
  for (const m of body.matchAll(/\{\{([^{}]*)\}\}/g)) {
    const name = m[1]!;
    if (!/^\w+$/.test(name)) return `Biến "${m[0]}" viết sai: chỉ gồm chữ không dấu, số và gạch dưới, không có dấu cách. ${hint}`;
    if (allowed && !allowed.includes(name)) return `Biến "{{${name}}}" không dùng được cho mẫu này, khách sẽ nhận câu bị trống chỗ đó. ${hint}`;
  }
  const single = /\{\w*\}/.exec(body.replace(/\{\{[^{}]*\}\}/g, ''));
  if (single) {
    return `"${single[0]}" chỉ có một dấu ngoặc nên khách sẽ thấy nguyên chữ đó. Biến phải nằm trong hai dấu ngoặc, ví dụ {{${allowed?.[0] ?? 'ten_bien'}}}.`;
  }
  return '';
}
