const BANNED: RegExp[] = [
  /tái chế/i,
  /hấp thụ/i,
  /giảm khí thải/i,
  /cây thật/i,
  /mua cây/i,
  /CO2/,
  /Mã chứng nhận/i,
  /voucher/i,
  /(^|[^\p{L}])xu([^\p{L}]|$)/iu,
  /điểm Xanh/,
  /xử lý đúng chuẩn/i,
  /Cộng tác viên không được làm điểm nhận/,
];

export function expectNoBannedCopy(text: string | null | undefined): void {
  const t = text ?? '';
  for (const re of BANNED) expect(t, `chữ cấm ${re}`).not.toMatch(re);
}

